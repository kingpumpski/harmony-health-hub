import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = path.join(root, "supabase", "migrations");
const markdownPath = path.join(root, "supabase-migration-list.txt");
const jsonPath = path.join(root, "supabase-migration-register.json");
const checkOnly = process.argv.includes("--check");

if (!fs.existsSync(migrationsDir)) {
  throw new Error(`Migration directory not found: ${migrationsDir}`);
}

const files = fs.readdirSync(migrationsDir)
  .filter((name) => name.toLowerCase().endsWith(".sql"))
  .sort((a, b) => a.localeCompare(b));

if (files.length === 0) throw new Error("No SQL migrations were found.");

const migrations = [];
const versions = new Map();
const invalid = [];

for (const file of files) {
  const match = /^(\d{14})_(.+)\.sql$/i.exec(file);
  if (!match) {
    invalid.push(file);
    continue;
  }
  const [, version, name] = match;
  if (versions.has(version)) {
    throw new Error(`Duplicate migration version ${version}: ${versions.get(version)} and ${file}`);
  }
  versions.set(version, file);
  const content = fs.readFileSync(path.join(migrationsDir, file));
  migrations.push({
    version,
    name,
    file,
    sha256: crypto.createHash("sha256").update(content).digest("hex"),
  });
}

if (invalid.length) {
  throw new Error(`Invalid migration filenames (expected YYYYMMDDHHMMSS_name.sql):\n- ${invalid.join("\n- ")}`);
}

migrations.sort((a, b) => a.version.localeCompare(b.version) || a.file.localeCompare(b.file));
const register = {
  schemaVersion: 1,
  source: "supabase/migrations",
  purpose: "Deterministic inventory of repository SQL migration files only; not proof of production application status.",
  migrationCount: migrations.length,
  migrations,
};
const json = `${JSON.stringify(register, null, 2)}\n`;
const lines = [
  "# Repository SQL Migration Inventory",
  "",
  "> Generated by `npm run migration:register`. This file lists repository files only; it does not represent Supabase remote application status.",
  "",
  `Total SQL migrations: **${migrations.length}**`,
  "",
  "| Version | Migration | SHA-256 |",
  "|---|---|---|",
  ...migrations.map((item) => `| ${item.version} | ${item.name} | \`${item.sha256}\` |`),
  "",
].join("\n");

if (checkOnly) {
  const existingMarkdown = fs.existsSync(markdownPath) ? fs.readFileSync(markdownPath, "utf8") : "";
  const existingJson = fs.existsSync(jsonPath) ? fs.readFileSync(jsonPath, "utf8") : "";
  if (existingMarkdown !== lines || existingJson !== json) {
    console.error("Migration register is stale. Run: npm run migration:register");
    process.exitCode = 1;
  } else {
    console.log(`[migration-register] ${migrations.length} files verified; register is current.`);
  }
} else {
  fs.writeFileSync(markdownPath, lines, "utf8");
  fs.writeFileSync(jsonPath, json, "utf8");
  console.log(`[migration-register] Generated register for ${migrations.length} SQL files.`);
}
